    Exception = { fg = syn.keyword },
    PreProc = { fg = syn.builtin },
    Include = { fg = syn.keyword },
    Define = { fg = syn.keyword },
    Macro = { fg = syn.builtin },
    Type = { fg = syn.type },
    StorageClass = { fg = syn.keyword },
