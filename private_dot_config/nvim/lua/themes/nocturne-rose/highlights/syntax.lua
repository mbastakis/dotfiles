    ["@variable"] = { fg = syn.text },
    ["@variable.builtin"] = { fg = syn.builtin },
    ["@variable.parameter"] = { fg = ui.text_dim, italic = true },
    ["@constant"] = { fg = syn.constant },
    ["@constant.builtin"] = { fg = syn.builtin },
